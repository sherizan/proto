import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'packages/proto-design');
const manifest = JSON.parse(fs.readFileSync(path.join(source, 'manifest.json'), 'utf8'));
const skill = fs.readFileSync(path.join(source, manifest.entry), 'utf8');
const body = skill.replace(/^---\n[\s\S]*?\n---\n+/, '').trim();
const hash = createHash('sha256').update(skill).digest('hex');
const guide = `<!-- Generated from prototo-design ${manifest.version}; sha256:${hash}. -->\n${body}\n`;
const pointer = `<!-- prototo-design:start -->\n## Shared design guidance\n\nFor screen design, redesign or motion, read .proto/design/GUIDE.md and apply it alongside this project's DESIGN.md. Preserve the user's direction and this host's tools and permissions.\n<!-- prototo-design:end -->`;
const check = process.argv.includes('--check');
let changed = false;
function output(file, expected) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === expected) return;
  if (check) { console.error('Design guidance is out of sync: ' + file); changed = true; return; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, expected);
}
function replaceBlock(file, block) {
  const old = fs.readFileSync(file, 'utf8');
  const start = '<!-- prototo-design:start -->', end = '<!-- prototo-design:end -->';
  const a = old.indexOf(start), b = old.indexOf(end);
  if ((a < 0) !== (b < 0) || (a >= 0 && (b < a || old.indexOf(start, a + start.length) >= 0 || old.indexOf(end, b + end.length) >= 0))) throw Error('Malformed design block: ' + file);
  output(file, a < 0 ? old.trimEnd() + '\n\n' + block + '\n' : old.slice(0, a) + block + old.slice(b + end.length));
}
output(path.join(root, 'packages/create-proto/template/.proto/design/GUIDE.md'), guide);
replaceBlock(path.join(root, 'packages/create-proto/template/AGENTS.md'), pointer);
output(path.join(root, 'packages/proto-cli/src/design-guidance-source.ts'), `// Generated by scripts/sync-design-guidance.mjs; edit packages/proto-design instead.\nexport const DESIGN_GUIDANCE_VERSION = ${JSON.stringify(manifest.version)};\nexport const DESIGN_GUIDANCE = ${JSON.stringify(guide)};\nexport const DESIGN_GUIDANCE_POINTER = ${JSON.stringify(pointer)};\n`);
const flag = process.argv.indexOf('--chatgpt');
if (flag >= 0) {
  const dest = process.argv[flag + 1];
  if (!dest || dest.startsWith('--')) throw Error('--chatgpt requires the repository path');
  const pluginSkill = path.resolve(dest, 'plugin/skills/prototo/SKILL.md');
  replaceBlock(pluginSkill, `<!-- prototo-design:start -->\n${guide.trim()}\n<!-- prototo-design:end -->`);
  output(path.resolve(dest, 'plugin/design-guidance.json'), JSON.stringify({ ...manifest, sha256: hash, embeddedSha256: createHash('sha256').update(guide.trim()).digest('hex') }, null, 2) + '\n');
}
if (changed) process.exitCode = 1;
else console.log(`Prototo design guidance ${manifest.version}: ${check ? 'verified' : 'synchronized'}`);
