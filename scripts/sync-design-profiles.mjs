import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
let drift = false;
const header = '// Generated by scripts/sync-design-profiles.mjs. Edit the canonical source.\n';
function output(relative, body) {
  const file = path.resolve(root, relative);
  const expected = header + body;
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === expected) return;
  if (check) { console.error('Design profile drift: ' + relative); drift = true; return; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, expected);
}
for (const file of fs.readdirSync(path.join(root, 'packages/proto-design/src')).filter(f => f.endsWith('.ts'))) {
  const source = fs.readFileSync(path.join(root, 'packages/proto-design/src', file), 'utf8');
  output('packages/proto-cli/src/design/' + file, source);
  if (['types.ts', 'typography.ts', 'contrast.ts'].includes(file)) output('packages/proto-components/src/design/' + file, source.replaceAll('.js\'', '\''));
}
let themes = "import type { Theme } from './types.js';\nimport { defaultTypography } from './typography.js';\n";
for (const name of ['base', 'liquidGlass', 'materialYou']) {
  themes += fs.readFileSync(path.join(root, `packages/proto-components/src/tokens/${name}.ts`), 'utf8').replace(/^import .*;\n/gm, '') + '\n';
}
themes += 'export const lightThemes = { base, liquidGlass, materialYou };\nexport const darkThemes = { base: baseDark, liquidGlass: liquidGlassDark, materialYou: materialYouDark };\n';
output('packages/proto-cli/src/design/themes.ts', themes);
const merge = fs.readFileSync(path.join(root, 'packages/proto-components/src/mergeTheme.ts'), 'utf8').replace("'./types'", "'./types.js'").replace("'./design/typography'", "'./typography.js'");
output('packages/proto-cli/src/design/mergeTheme.ts', merge);
const chatgptFlag = process.argv.indexOf('--chatgpt');
if (chatgptFlag >= 0) {
  const target = process.argv[chatgptFlag + 1];
  if (!target || target.startsWith('--')) throw Error('--chatgpt requires a repository path');
  for (const file of fs.readdirSync(path.join(root, 'packages/proto-cli/src/design')).filter(f => f.endsWith('.ts'))) {
    const body = fs.readFileSync(path.join(root, 'packages/proto-cli/src/design', file), 'utf8').replace(header, '');
    output(path.resolve(target, 'src/design', file), body);
  }
  const runtimeFiles = ['types.ts', 'design/types.ts', 'design/typography.ts', 'design/contrast.ts', 'design/capabilities.json', 'Button.tsx', 'Screen.tsx', 'PurchaseAction.tsx', 'Skeleton.tsx', 'index.ts', 'Text.tsx', 'ProtoConfigContext.tsx', 'useTheme.ts', 'mergeTheme.ts', 'tokens/base.ts', 'tokens/liquidGlass.ts', 'tokens/materialYou.ts'];
  const runtime = Object.fromEntries(runtimeFiles.map(file => [file, fs.readFileSync(path.join(root, 'packages/proto-components/src', file), 'utf8')]));
  output(path.resolve(target, 'src/design-runtime-source.ts'), 'export const designRuntimeFiles: Record<string, string> = ' + JSON.stringify(runtime, null, 2) + ';\n');
}
if (drift) process.exitCode = 1;
else console.log('Shared design profile sources ' + (check ? 'verified' : 'synchronized'));
